-- 장소 행은 여러 쓰기가 함께 고친다. 제보자의 박지 수정, 관리자 숨김·복구, 박지 신고·확인, 박지 재판정, 공공데이터 동기화다.
-- 그런데 박지 수정은 행을 잠그지 않고 읽은 뒤 모든 열을 다시 쓴다. 그래서 그 사이 재판정이 바꾼 공원 경계 판정이나 관리자가 바꾼 상태를
-- 읽은 값으로 덮어쓸 수 있었다(같은 순서로 끼워 넣은 재현 테스트에서 매번 재현됐다).
-- version은 행을 바꿀 때마다 1씩 올리는 낙관적 잠금 번호다. JPA는 엔티티를 쓸 때 읽은 번호와 같을 때만 쓰고, MyBatis로 장소 행을 바꾸는 SQL도
-- 모두 번호를 올린다. 그래서 누가 먼저 바꿨는지와 상관없이, 낡은 값으로 쓰려는 쪽이 실패를 알아차린다.
ALTER TABLE spot
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
